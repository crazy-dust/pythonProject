# 十四、练习与验收
# 练习 1：协程与并发（⭐⭐⭐⭐⭐）
# 写 5 个协程，每个等待 1 秒并返回自己的编号。分别使用顺序 await 和 gather，观察总耗时。
# 验收： 能解释为什么一个约 5 秒，一个约 1 秒。
#
#
# 练习 2：限流（⭐⭐⭐⭐⭐）
# 模拟 20 个 HTTP 请求，每个请求等待 0.5 秒，使用 Semaphore(4) 限制并发。
# 验收： 同时进行的请求不超过 4 个。
#
#
# 练习 3：超时与失败隔离（⭐⭐⭐⭐⭐）
# 让第 3 个请求抛出 ValueError，第 7 个请求等待 3 秒，其余请求等待 0.2 秒。设置 1 秒超时，最终输出成功、失败、超时的数量。
# 验收： 一个订单失败不会让其他订单全部失败。
#
#
# 练习 4：生产者消费者（⭐⭐⭐⭐）
# 使用 asyncio.Queue(maxsize=5)，一个生产者生成 100 个订单，3 个消费者处理订单，并正确使用结束哨兵和 task_done()。
# 验收： 所有订单恰好处理一次，程序可以正常退出。
#
#
# 练习 5：同步代码接入（⭐⭐⭐⭐）
# 写一个使用 time.sleep(2) 的同步函数，再分别直接在协程中调用、通过 asyncio.to_thread() 调用，对比三个任务的耗时。
# 验收： 能解释为什么 to_thread 可以避免同步 I/O 阻塞事件循环。
